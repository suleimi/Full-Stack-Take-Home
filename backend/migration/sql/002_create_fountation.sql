-- Why we use emission_rollup_MONTHLY:
--   * It is the smallest rollup table (~13k rows/year, whole platform), so even
--     summing an entity's entire history touches only a handful of rows.
--   * The current month's bucket already contains everything rolled up so far
--     this month -- so a sum of monthly buckets is correct "to date" without
--     adding daily/hourly buckets on top (that would double-count).
--   * It already holds org/site/asset rows, so any entity level is a direct
--     lookup -- an org total needs no summing of its assets.
 
 
-- LIFETIME total emitted, per entity, from the beginning of time through now.
-- This is "total emission till date" -- a pure cumulative figure, independent
-- of any policy or period window.
CREATE VIEW emission_total_to_date AS
SELECT entity_type,
       entity_id,
       SUM(total_emission)  AS total_to_date,
       SUM(reading_count)   AS reading_count,
       MAX(computed_at)     AS as_of
FROM emission_rollup_monthly
GROUP BY entity_type, entity_id;
-- Usage:  SELECT * FROM emission_total_to_date
--         WHERE entity_type = $1 AND entity_id = $2;

